const SUPPORTED_LANGUAGES = ["fr", "en", "zh", "it", "de"];

function detectLanguage() {
  try {
    const stored = localStorage.getItem("w2b-lang");
    if (stored && SUPPORTED_LANGUAGES.includes(stored)) return stored;
  } catch { /* localStorage indisponible */ }
  const browserLang = (navigator.language || "fr").slice(0, 2).toLowerCase();
  return SUPPORTED_LANGUAGES.includes(browserLang) ? browserLang : "fr";
}

const state_i18n = { lang: detectLanguage() };

function t(key, vars) {
  const dict = I18N[state_i18n.lang] || I18N.fr;
  let text = dict[key] ?? I18N.fr[key] ?? key;
  if (vars) {
    Object.entries(vars).forEach(([name, value]) => {
      text = text.replace(new RegExp(`\\{${name}\\}`, "g"), value);
    });
  }
  return text;
}

function setLanguage(lang) {
  if (!SUPPORTED_LANGUAGES.includes(lang)) return;
  state_i18n.lang = lang;
  try { localStorage.setItem("w2b-lang", lang); } catch { /* localStorage indisponible */ }
  document.documentElement.lang = lang;
  applyTranslations();
}

function applyTranslations() {
  document.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  document.querySelectorAll("[data-i18n-aria-label]").forEach((el) => { el.setAttribute("aria-label", t(el.dataset.i18nAriaLabel)); });
}
